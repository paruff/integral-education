#!/usr/bin/env node
// Writes src/data/pathways.json: each QuickStart's ordered module ids, read from the
// step table in its "Plan your pathway" section. My Progress uses it to show pathway
// completion (FR-19) without a second, hand-kept list. Also writes src/data/moduleNav.js:
// each module's QuickStart and "Next:" link in step order (ModuleFooter). A module in
// several QuickStarts uses the first one alphabetically. tests/pathways.test.mjs fails
// if either committed file is stale.
// Usage: node scripts/generate-pathways.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = 'docs/quickstarts';
const OUT = 'src/data/pathways.json';
const NAV_OUT = 'src/data/moduleNav.js';
const MODULES = 'docs/modules';

export function buildPathways(dir = DIR) {
  return readdirSync(dir)
    .filter((f) => /\.mdx?$/.test(f))
    .sort()
    .map((f) => {
      const text = readFileSync(`${dir}/${f}`, 'utf8');
      const plan = text.match(/^## Plan your pathway[^\n]*\n([\s\S]*?)(?=^## |(?![\s\S]))/m)?.[1] ?? '';
      const modules = [...plan.matchAll(/^\|\s*\d+\s*\|\s*\[[^\]]+\]\(\.\.\/modules\/([a-z0-9-]+)\)/gm)].map((m) => m[1]);
      const label = text.match(/^sidebar_label:\s*(.+)$/m)?.[1] ?? text.match(/^title:\s*(.+)$/m)?.[1] ?? f;
      return { id: f.replace(/\.mdx?$/, ''), title: label.replace(/\s*\(QuickStart\)\s*$/, '').trim(), modules };
    })
    .filter((p) => p.modules.length);
}

const docTitle = (id) => {
  const f = ['.mdx', '.md'].map((e) => `${MODULES}/${id}${e}`).find((p) => existsSync(p));
  const text = readFileSync(f, 'utf8');
  const get = (k) => text.match(new RegExp(`^${k}:\\s*['"]?(.+?)['"]?\\s*$`, 'm'))?.[1].replace(/''/g, "'");
  return get('sidebar_label') ?? get('title');
};

export function buildModuleNav(pathways) {
  const nav = {};
  const quickstarts = {};
  for (const { id, title, modules } of pathways) {
    quickstarts[id] = { title, to: `/docs/quickstarts/${id}` };
    modules.forEach((m, i) => {
      const n = modules[i + 1];
      nav[m] ??= { quickstart: id, next: n ? { title: docTitle(n), to: `/docs/modules/${n}` } : null };
    });
  }
  return { nav, quickstarts };
}

export const renderNav = ({ nav, quickstarts }) =>
  `// Generated by scripts/generate-pathways.mjs from the QuickStart step tables. Do not edit.\n` +
  `export const QUICKSTARTS = ${JSON.stringify(quickstarts, null, 2)};\n\n` +
  `export default ${JSON.stringify(nav, null, 2)};\n`;

export const render = (pathways) => JSON.stringify(pathways, null, 2) + '\n';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pathways = buildPathways();
  const files = [[OUT, render(pathways)], [NAV_OUT, renderNav(buildModuleNav(pathways))]];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([f, next]) => readFileSync(f, 'utf8') !== next);
    if (stale.length) {
      console.error(`❌ ${stale.map(([f]) => f).join(', ')} out of date. Run: node scripts/generate-pathways.mjs`);
      process.exit(1);
    }
    console.log('✅ pathways.json and moduleNav.js are up to date');
  } else {
    for (const [f, next] of files) writeFileSync(f, next);
    console.log(`Wrote ${files.map(([f]) => f).join(', ')}`);
  }
}
